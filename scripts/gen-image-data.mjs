// Reads public/cats/*.webp (transparent cutouts), emits src/lib/catImages.ts
// with src + intrinsic dimensions. No blur placeholder (cutouts are transparent).
import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(__dirname, "..", "public", "cats");

const files = (await readdir(DIR)).filter((f) => f.endsWith(".webp")).sort();
const entries = [];
for (const f of files) {
  const id = f.replace(/\.webp$/, "");
  const meta = await sharp(path.join(DIR, f)).metadata();
  entries.push({ id, width: meta.width, height: meta.height });
}
const body = entries
  .map((e) => `  "${e.id}": { src: "/cats/${e.id}.webp", width: ${e.width}, height: ${e.height} },`)
  .join("\n");
const ts =
  `// AUTO-GENERATED by scripts/gen-image-data.mjs — do not edit by hand.\n\n` +
  `export interface CatImage {\n  src: string;\n  width: number;\n  height: number;\n}\n\n` +
  `export const CAT_IMAGES: Record<string, CatImage> = {\n${body}\n};\n`;
await writeFile(path.join(__dirname, "..", "src", "lib", "catImages.ts"), ts);
console.log(`Wrote catImages.ts with ${entries.length} cutouts.`);

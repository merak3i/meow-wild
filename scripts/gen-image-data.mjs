// Reads public/cats/*.webp, emits src/lib/catImages.ts with src, dimensions, and a
// tiny base64 blur placeholder per cat (for next/image placeholder="blur").
import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(__dirname, "..", "public", "cats");

const files = (await readdir(DIR)).filter((f) => f.endsWith(".webp")).sort();
const entries = [];
for (const f of files) {
  const id = f.replace(/\.webp$/, "");
  const full = path.join(DIR, f);
  const meta = await sharp(full).metadata();
  const blurBuf = await sharp(full).resize(24).webp({ quality: 35 }).toBuffer();
  const blur = `data:image/webp;base64,${blurBuf.toString("base64")}`;
  entries.push({ id, width: meta.width, height: meta.height, blur });
}

const body = entries
  .map(
    (e) =>
      `  "${e.id}": { src: "/cats/${e.id}.webp", width: ${e.width}, height: ${e.height}, blurDataURL: "${e.blur}" },`,
  )
  .join("\n");

const ts =
  `// AUTO-GENERATED by scripts/gen-image-data.mjs — do not edit by hand.\n` +
  `// Run \`node scripts/gen-image-data.mjs\` after changing photos in public/cats/.\n\n` +
  `export interface CatImage {\n  src: string;\n  width: number;\n  height: number;\n  blurDataURL: string;\n}\n\n` +
  `export const CAT_IMAGES: Record<string, CatImage> = {\n${body}\n};\n`;

await writeFile(path.join(__dirname, "..", "src", "lib", "catImages.ts"), ts);
console.log(`Wrote src/lib/catImages.ts with ${entries.length} entries.`);
